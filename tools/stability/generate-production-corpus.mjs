import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { cases, requiredFeatures } from "./production-corpus.mjs";

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(toolDirectory, "../..");
const outputs = [
    {
        packageName: "com.swithun.jsxgraph.core.generated",
        path: resolve(
            repositoryRoot,
            "jsxgraph-core/src/commonTest/kotlin/" +
                "com/swithun/jsxgraph/core/generated/ProductionCorpus.kt"
        )
    },
    {
        packageName: "com.swithun.jsxgraph.debugui.generated",
        path: resolve(
            repositoryRoot,
            "jsxgraph-debug-ui/src/commonMain/kotlin/" +
                "com/swithun/jsxgraph/debugui/generated/ProductionCorpus.kt"
        )
    }
];

validateCorpus();
for (const output of outputs) {
    mkdirSync(dirname(output.path), {recursive: true});
    writeFileSync(output.path, renderKotlin(output.packageName));
    console.log(`Generated ${output.path}`);
}

function validateCorpus() {
    if (cases.length !== 30) {
        throw new Error(`Expected 30 production cases, found ${cases.length}`);
    }
    if (new Set(requiredFeatures).size !== requiredFeatures.length) {
        throw new Error("Required production features must be unique");
    }

    const knownFeatures = new Set(requiredFeatures);
    const coveredFeatures = new Set();
    const ids = new Set();
    const sources = new Set();
    for (const entry of cases) {
        if (!/^prod_[a-z0-9_]+$/.test(entry.id)) {
            throw new Error(`Invalid production case id: ${entry.id}`);
        }
        if (ids.has(entry.id)) {
            throw new Error(`Duplicate production case id: ${entry.id}`);
        }
        if (entry.title.trim().length === 0 || entry.scenario.trim().length === 0) {
            throw new Error(`Missing title or scenario for ${entry.id}`);
        }
        if (sources.has(entry.source)) {
            throw new Error(`Duplicate production source for ${entry.id}`);
        }
        const document = JSON.parse(entry.source);
        if (
            document.schemaVersion !== 1 ||
            !Array.isArray(document.objects) ||
            document.objects.length === 0
        ) {
            throw new Error(`Invalid construction document for ${entry.id}`);
        }
        const objectIds = new Set(document.objects.map((object) => object.id));
        if (objectIds.size !== document.objects.length) {
            throw new Error(`Duplicate object id in ${entry.id}`);
        }
        for (const expectedId of entry.expectedElementIds) {
            if (!objectIds.has(expectedId)) {
                throw new Error(
                    `${entry.id} expects missing element id ${expectedId}`
                );
            }
        }
        for (const expectedText of entry.expectedTexts) {
            if (!entry.source.includes(expectedText.split(" = ")[0])) {
                throw new Error(
                    `${entry.id} expects text absent from source: ${expectedText}`
                );
            }
        }
        if (!Array.isArray(entry.features) || entry.features.length === 0) {
            throw new Error(`Missing feature coverage for ${entry.id}`);
        }
        for (const feature of entry.features) {
            if (!knownFeatures.has(feature)) {
                throw new Error(`${entry.id} declares unknown feature ${feature}`);
            }
            coveredFeatures.add(feature);
        }
        validateInteraction(entry, objectIds);
        ids.add(entry.id);
        sources.add(entry.source);
    }

    const missingFeatures = requiredFeatures.filter(
        (feature) => !coveredFeatures.has(feature)
    );
    if (missingFeatures.length > 0) {
        throw new Error(
            `Missing production feature coverage: ${missingFeatures.join(", ")}`
        );
    }
}

function validateInteraction(entry, objectIds) {
    if (entry.interaction === null) {
        return;
    }
    if (!objectIds.has(entry.interaction.pointId)) {
        throw new Error(
            `${entry.id} interaction references missing point ` +
                entry.interaction.pointId
        );
    }
    if (
        !Array.isArray(entry.interaction.target) ||
        entry.interaction.target.length !== 2 ||
        !entry.interaction.target.every(Number.isFinite)
    ) {
        throw new Error(`Invalid interaction target for ${entry.id}`);
    }
}

function renderKotlin(packageName) {
    return `// Generated by tools/stability/generate-production-corpus.mjs.
// Do not edit by hand.
package ${packageName}

internal data class ProductionCorpusCase(
    val id: String,
    val title: String,
    val scenario: String,
    val source: String,
    val expectedElementIds: Set<String>,
    val expectedTexts: List<String>,
    val features: Set<String>,
    val interactionPointId: String?,
    val interactionTargetX: Double?,
    val interactionTargetY: Double?,
)

internal val requiredProductionFeatures: Set<String> = ${renderStringSet(
        requiredFeatures
    )}

internal val productionCorpusCases: List<ProductionCorpusCase> = listOf(
${cases.map(renderCase).join(",\n")}
)
`;
}

function renderCase(entry) {
    const interaction = entry.interaction;
    return `    ProductionCorpusCase(
        id = ${quote(entry.id)},
        title = ${quote(entry.title)},
        scenario = ${quote(entry.scenario)},
        source = """
${indent(entry.source, 12)}
        """.trimIndent(),
        expectedElementIds = ${renderStringSet(entry.expectedElementIds, 8)},
        expectedTexts = ${renderStringList(entry.expectedTexts, 8)},
        features = ${renderStringSet(entry.features, 8)},
        interactionPointId = ${
            interaction === null ? "null" : quote(interaction.pointId)
        },
        interactionTargetX = ${
            interaction === null ? "null" : renderDouble(interaction.target[0])
        },
        interactionTargetY = ${
            interaction === null ? "null" : renderDouble(interaction.target[1])
        },
    )`;
}

function renderStringSet(values, baseIndent = 0) {
    if (values.length === 0) {
        return "emptySet()";
    }
    const prefix = " ".repeat(baseIndent);
    const childPrefix = " ".repeat(baseIndent + 4);
    return `setOf(\n${values
        .map((value) => `${childPrefix}${quote(value)},`)
        .join("\n")}\n${prefix})`;
}

function renderStringList(values, baseIndent = 0) {
    if (values.length === 0) {
        return "emptyList()";
    }
    const prefix = " ".repeat(baseIndent);
    const childPrefix = " ".repeat(baseIndent + 4);
    return `listOf(\n${values
        .map((value) => `${childPrefix}${quote(value)},`)
        .join("\n")}\n${prefix})`;
}

function renderDouble(value) {
    return Number.isInteger(value) ? `${value}.0` : String(value);
}

function quote(value) {
    return JSON.stringify(value);
}

function indent(value, spaces) {
    const prefix = " ".repeat(spaces);
    return value.split("\n").map((line) => `${prefix}${line}`).join("\n");
}
